#!/usr/bin/env python3
"""Audit (default) or scaffold (--init) a repository's documentation system.

Standard library only, no network, never overwrites a file. File content is treated as data.
Usage: python3 docs_audit.py [--root DIR] [--init] [--map] [--install-hook] [--changed BASE]
--map regenerates docs/MAP.md, the knowledge map; the audit fails while it is missing or stale.
--install-hook adds a git pre-commit hook that does that on every commit with a Markdown change.
Exit code: 1 if any ERROR (a required piece is missing, a relative link is broken, or with --changed
a required doc did not change with the code), 2 if BASE cannot be read, else 0.
This checks structure and co-change only. Whether the docs are true is a reading job: see SKILL.md.
"""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote, unquote

SELF = Path(__file__).resolve()
TEMPLATES = SELF.parent.parent / "templates"
MARKER = "TODO(docs)"
# section -> other places that count as having it (so an existing layout is not duplicated)
SECTIONS = {
    "architecture": [], "decisions": [], "explanation": [], "how-to": [], "learning": [],
    "reference": [], "security": [], "tutorials": [],
    "governance": ["GOVERNANCE.md"],
    "progress": ["docs/plan", "ROADMAP.md"],
}
# sections that are collections: a README alone means "nothing written yet"
COLLECTIONS = {"decisions", "explanation", "how-to", "learning", "reference", "tutorials"}
FENCE = re.compile(r"^(```|~~~).*?^\1", re.S | re.M)
INLINE = re.compile(r"`[^`\n]*`")
LINK = re.compile(r"\[[^\]]*\]\((?:<([^>]+)>|((?:[^()\s]|\([^()\s]*\))+))(?:\s+\"[^\"]*\")?\)")
STATUS = re.compile(r"^(?:status:|[-*\s]*\*\*Status:?\*\*:?)\s*(\S.*)$", re.M | re.I)
MAP = "docs/MAP.md"
MAP_MARK = "Generated by docs_audit.py --map"
MAP_HEADER = (
    "# Knowledge map\n\n"
    "<!-- %s. Do not edit by hand: run `python3 scripts/docs_audit.py --map` and commit the result. "
    "The docs audit fails if this file is stale. -->\n\n"
    "Every Markdown file in the project, with its title, ADR status, and the files that link to it. "
    "Only relative Markdown links are counted." % MAP_MARK
)
MD_ESCAPE = re.compile(r"([\\`*_{}\[\]<>()#+!|~&])")  # Markdown syntax in titles is shown, never interpreted
ADR_DIRS = ("docs/decisions/", "docs/adr/")
README_MAX_LINES = 150  # shortcut: one fixed limit for every repo; make it per-repo if a README needs more


def md_files(root):
    files = sorted(p for p in root.glob("*.md") if p.is_file())
    return files + sorted(p for p in (root / "docs").rglob("*.md") if p.is_file())


def has_md(path):
    return path.is_file() or (path.is_dir() and any(path.rglob("*.md")))


def section_home(root, name):
    """Return the path that provides this section, or None."""
    for cand in ["docs/" + name] + SECTIONS[name]:
        if has_md(root / cand):
            return root / cand
    return None


def links(path, root):
    """Yield (target text, resolved path or None if outside the repo) for each relative link."""
    text = INLINE.sub("", FENCE.sub("", path.read_text(encoding="utf-8", errors="replace")))
    for m in LINK.finditer(text):
        target = m.group(1) or m.group(2)
        if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:|^#", target):
            continue  # external URL, mailto:, or in-page anchor
        clean = re.split(r"[#?]", unquote(target))[0]
        if clean:
            dest = (path.parent / clean).resolve()
            yield target, dest if root in dest.parents or dest == root else None


def generate_map(root):
    """The text of docs/MAP.md: every Markdown file, its title, ADR status and backlinks."""
    root = root.resolve()
    r = subprocess.run(["git", "-C", str(root), "ls-files", "--cached", "-z"], capture_output=True, text=True)
    known = {(root / p).resolve() for p in r.stdout.split("\0") if p} if r.returncode == 0 else None
    # in a git repository only tracked or staged files count, so local scratch files never reach the map
    files = [f for f in md_files(root) if f != root / MAP and (known is None or f in known)]
    rel = {f: f.relative_to(root).as_posix() for f in files}
    info, backlinks = {}, {f: set() for f in files}
    for f in files:
        text = f.read_text(encoding="utf-8", errors="replace")
        body = text
        if text.startswith("---\n") and text.find("\n---", 4) != -1:
            body = text[text.find("\n---", 4) + 4:]  # skip front matter
        title = re.search(r"^# +(.+?)\s*$", FENCE.sub("", body), re.M)
        status = None
        if rel[f].startswith(ADR_DIRS) and STATUS.search(text):
            word = re.match(r"[\w -]*\w", STATUS.search(text).group(1))  # "Accepted, 2026-…" -> "Accepted"
            status = word.group(0) if word else None
        info[f] = (title.group(1) if title else rel[f], status)
        for _, dest in links(f, root):
            if dest in backlinks and dest != f:
                backlinks[dest].add(f)

    esc = lambda text: MD_ESCAPE.sub(r"\\\1", text)
    href = lambda f: quote(rel[f][5:] if rel[f].startswith("docs/") else "../" + rel[f], safe="/")
    groups = {}
    for f in files:
        parent = Path(rel[f]).parent.as_posix()
        groups.setdefault("root" if parent == "." else parent, []).append(f)
    out = [MAP_HEADER]
    for name in sorted(groups, key=lambda g: (g != "root", g)):
        out.append("\n## %s\n" % esc(name))
        for f in groups[name]:
            title, status = info[f]
            line = "- [%s](%s): %s" % (esc(rel[f]), href(f), esc(title))
            out.append(line + (" (status: %s)" % esc(status) if status else ""))
            if backlinks[f]:
                out.append("  - Linked from: " + ", ".join(
                    "[%s](%s)" % (esc(rel[b]), href(b)) for b in sorted(backlinks[f], key=rel.get)))
    return "\n".join(out) + "\n"


def write_map(root):
    (root / MAP).parent.mkdir(parents=True, exist_ok=True)
    (root / MAP).write_text(generate_map(root), encoding="utf-8")


def map_findings(root):
    path = root.resolve() / MAP
    if not path.is_file():
        return [("ERROR", MAP, "missing: run `python3 scripts/docs_audit.py --map` and commit it")]
    text = path.read_text(encoding="utf-8", errors="replace")
    if MAP_MARK not in text:
        return [("INFO", MAP, "made by the repository's own generator: not checked here")]
    if text != generate_map(root):
        return [("ERROR", MAP, "stale: run `python3 scripts/docs_audit.py --map` and commit it")]
    return []


PRE_COMMIT = """#!/bin/sh
# docs-system: regenerate docs/MAP.md and add it to this commit (installed by docs_audit.py).
# Never blocks a commit: CI's docs check is the backstop.
# shortcut: the map is built from the working tree, so unstaged doc edits show in it; upgrade if that ever misleads.
root=$(git rev-parse --show-toplevel) || exit 0
[ -f "$root/scripts/docs_audit.py" ] && [ -f "$root/docs/MAP.md" ] || exit 0
grep -q '%s' "$root/docs/MAP.md" || exit 0   # a map made by the repository's own generator is left alone
git diff --cached --name-only | grep -q '\\.md$' || exit 0
python3 -c 'import sys, pathlib; sys.path.insert(0, sys.argv[1]); import docs_audit; docs_audit.write_map(pathlib.Path(sys.argv[2]))' \\
  "$root/scripts" "$root" || exit 0
git add "$root/docs/MAP.md"
""" % MAP_MARK


def install_hook(root):
    """Install the pre-commit hook that keeps the map current. Returns the hook path, or None if not installed."""
    r = subprocess.run(["git", "-C", str(root), "rev-parse", "--git-path", "hooks"], capture_output=True, text=True)
    if r.returncode:
        return None  # not a git repository
    hook = (root / r.stdout.strip() / "pre-commit").resolve()
    if hook.exists() and MAP_MARK not in hook.read_text(encoding="utf-8", errors="replace"):
        return None  # someone else's pre-commit hook: never overwritten
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(PRE_COMMIT, encoding="utf-8")
    hook.chmod(0o755)
    return hook


def audit(root):
    root = root.resolve()
    out = []  # (level, path, message)
    add = lambda level, path, msg: out.append((level, path, msg))
    docs = root / "docs"

    for name in ("README.md", "CHANGELOG.md", "SECURITY.md"):
        if not (root / name).is_file():
            add("ERROR", name, "missing")
    if not any((root / n).is_file() for n in ("CLAUDE.md", "AGENTS.md", ".claude/CLAUDE.md")):
        add("WARN", "CLAUDE.md", "no CLAUDE.md or AGENTS.md: AI assistants get no project instructions")
    readme = root / "README.md"
    if readme.is_file():
        lines = len(readme.read_text(encoding="utf-8", errors="replace").splitlines())
        if lines > README_MAX_LINES:
            add("WARN", "README.md", "%d lines: keep it a landing page; move steps to docs/how-to/, background to "
                "docs/explanation/, facts to docs/reference/, status to the progress folder (SKILL.md)" % lines)
    changelog = root / "CHANGELOG.md"
    if changelog.is_file() and "unreleased" not in changelog.read_text(encoding="utf-8", errors="replace").lower():
        add("WARN", "CHANGELOG.md", "no Unreleased section (Keep a Changelog)")

    index = next((p for p in (docs / "README.md", docs / "MAP.md") if p.is_file()), docs / "README.md")
    if not index.is_file():
        add("ERROR", "docs/README.md", "missing: no index of the documentation (docs/MAP.md also counts)")
    indexed = {d for _, d in links(index, root)} if index.is_file() else set()
    for name in SECTIONS:
        home = section_home(root, name)
        rel = "docs/%s/" % name
        if home is None:
            add("ERROR", rel, "missing section")
            continue
        if home != docs / name:
            add("INFO", rel, "provided by %s" % home.relative_to(root).as_posix())
        elif name in COLLECTIONS and not [
            p for p in home.rglob("*.md") if p.name != "README.md" and "template" not in p.name
        ]:
            add("INFO", rel, "empty: only a README or template so far")
        if index.is_file() and not any(d and (d == home or home in d.parents) for d in indexed):
            add("WARN", index.relative_to(root).as_posix(), "does not link to %s" % home.relative_to(root).as_posix())
    for name, level in (("verification-backlog.md", "WARN"), ("glossary.md", "INFO")):
        if not (docs / name).is_file():
            add(level, "docs/" + name, "missing")

    files = md_files(root)
    inbound = {f: set() for f in files}
    for f in files:
        rel = f.relative_to(root).as_posix()
        text = f.read_text(encoding="utf-8", errors="replace")
        for n, line in enumerate(text.splitlines(), 1):
            if MARKER in line:
                add("WARN", "%s:%d" % (rel, n), "unfilled scaffold placeholder")
        for target, dest in links(f, root):
            if dest is None:
                continue  # points outside the repository
            if not dest.exists():
                add("ERROR", rel, "broken link: %s" % target)
            elif f != root / MAP:  # the map links everything, so it must not hide orphans
                for hit in (dest.glob("*.md") if dest.is_dir() else [dest]):  # a folder link reaches its files
                    if hit in inbound and hit != f:
                        inbound[hit].add(f)

    out.extend(map_findings(root))
    copy = root / "scripts" / "docs_audit.py"
    if copy.is_file() and copy.resolve() != SELF and copy.read_bytes() != SELF.read_bytes():
        add("WARN", "scripts/docs_audit.py", "differs from the docs-system skill's copy: copy %s over it" % SELF)

    decisions = docs / "decisions"
    for f in files:
        rel = f.relative_to(root).as_posix()
        skip = f.name in ("README.md", "MAP.md") or "template" in f.name
        if docs in f.parents and not skip and not inbound[f]:
            add("WARN", rel, "orphan: no other Markdown file links to it")
        if f.parent == decisions and not skip:
            if not STATUS.search(f.read_text(encoding="utf-8", errors="replace")):
                add("WARN", rel, "ADR has no status")
            if (decisions / "README.md").is_file() and decisions / "README.md" not in inbound[f]:
                add("WARN", rel, "ADR is not in the index (docs/decisions/README.md)")
    return out


# shortcut: fixed rule lists for every repo; move them to a per-repo config when one repo needs different ones
MANIFESTS = {"pyproject.toml", "requirements.txt", "Pipfile", "package.json", "Cargo.toml", "go.mod",
             "Gemfile", "environment.yml", "requirements-dev.txt"}
SENSITIVE = re.compile(r"auth|login|secur|crypt|secret|token|session|permission|migration|storage", re.I)
ESCAPE = re.compile(r"^Docs:\s*none needed", re.I | re.M)


def git(root, *args):
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)
    if r.returncode:
        raise ValueError("git %s failed: %s" % (" ".join(args), r.stderr.strip()))
    return r.stdout


def changed(root, base):
    """Findings for docs that should have changed alongside the code changed since BASE.

    Changed = committed since BASE + staged + unstaged + untracked (not ignored) files.
    Raises ValueError if BASE is not a commit or ROOT is not a git repository.
    """
    git(root, "rev-parse", "--verify", base + "^{commit}")
    fork = git(root, "merge-base", base, "HEAD").strip()  # ignore commits that landed on BASE after branching
    parts = git(root, "diff", "--name-status", "--no-renames", "-z", fork).split("\0")
    status = dict(zip(parts[1::2], parts[0::2]))  # path -> A/M/D
    for p in git(root, "ls-files", "--others", "--exclude-standard", "-z").split("\0"):
        status.setdefault(p, "A")
    status.pop("", None)

    def is_doc(p):
        return p.startswith("docs/") or ("/" not in p and p.endswith(".md"))

    # shortcut: dot-paths (.github/, .claude/) are not treated as code; add them if CI changes need ADRs
    code = [p for p in status if not is_doc(p) and not p.startswith(".")]
    touched = lambda prefix: any(p.startswith(prefix) for p in status)
    out = []
    add = lambda level, path, msg: out.append((level, path, msg))
    if code and "CHANGELOG.md" not in status:
        add("ERROR", "CHANGELOG.md", "%d code file(s) changed but no changelog entry" % len(code))
    deps = [p for p in code if p.rsplit("/", 1)[-1] in MANIFESTS]
    adrs = [p for p in status if p.startswith(("docs/decisions/", "docs/adr/")) and p.endswith(".md")
            and not p.endswith("README.md") and "template" not in p]
    if deps and not adrs:
        add("ERROR", "docs/decisions/", "dependency manifest changed (%s) but no ADR added or changed" % ", ".join(deps))
    new = [p for p in code if status[p] == "A" and p not in deps]
    if new and not touched("docs/architecture/"):
        add("WARN", "docs/architecture/", "new file(s) %s but architecture docs unchanged" % ", ".join(new[:3]))
    risky = [p for p in code if SENSITIVE.search(p)]
    if risky and "docs/security/threat-model.md" not in status:
        add("WARN", "docs/security/threat-model.md", "security-relevant path(s) %s changed but threat model unchanged"
            % ", ".join(risky[:3]))

    if ESCAPE.search(git(root, "log", "--format=%B", fork + "..HEAD")):
        out = [("INFO" if lv == "ERROR" else lv, p, m + " (allowed: 'Docs: none needed' in a commit message)"
                if lv == "ERROR" else m) for lv, p, m in out]
    return out


def init(root):
    """Copy each template file that does not exist yet. Returns the list of files created."""
    created = []
    workflows = root / ".github" / "workflows"
    has_check = workflows.is_dir() and any("docs_audit.py" in p.read_text(encoding="utf-8", errors="replace")
                                           for p in workflows.glob("*.y*ml"))
    copy = root / "scripts" / "docs_audit.py"
    if not copy.exists():  # CI cannot see ~/.claude, so the repo carries its own copy
        copy.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(SELF, copy)
        created.append("scripts/docs_audit.py")
    for src in sorted(p for p in TEMPLATES.rglob("*") if p.is_file()):
        rel = src.relative_to(TEMPLATES)
        parts = rel.parts
        if parts[0] == ".github" and has_check:
            continue  # an existing workflow already runs the check
        if parts[0] == "docs" and len(parts) > 2 and parts[1] in SECTIONS:
            home = section_home(root, parts[1])
            if home is not None and home != root / "docs" / parts[1]:
                continue  # section already lives elsewhere (for example a root GOVERNANCE.md)
        dest = root / rel
        if not dest.exists():
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
            created.append(rel.as_posix())
    if not (root / MAP).exists():  # last, so it lists the files just created; an existing map is never touched
        write_map(root)
        created.append(MAP)
    if MAP_MARK in (root / MAP).read_text(encoding="utf-8", errors="replace") and install_hook(root):
        created.append("git pre-commit hook (keeps docs/MAP.md current)")
    return created


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=Path.cwd())
    ap.add_argument("--init", action="store_true", help="create missing files from templates, then audit")
    ap.add_argument("--changed", metavar="BASE",
                    help="also check that docs changed with the code changed since git ref BASE (e.g. origin/main, HEAD)")
    ap.add_argument("--map", action="store_true", help="regenerate docs/MAP.md (the knowledge map), then audit")
    ap.add_argument("--install-hook", action="store_true",
                    help="install the git pre-commit hook that regenerates and commits docs/MAP.md automatically")
    args = ap.parse_args(argv)
    if not args.root.is_dir():
        print("not a directory: %s" % args.root, file=sys.stderr)
        return 2
    if args.init:
        for path in init(args.root):
            print("CREATED %s" % path)
    if args.map:
        existing = args.root / MAP
        if existing.is_file() and MAP_MARK not in existing.read_text(encoding="utf-8", errors="replace"):
            print("refusing: %s is made by the repository's own generator" % MAP, file=sys.stderr)
            return 2
        write_map(args.root)
        print("WROTE %s" % MAP)
    if args.install_hook:
        hook = install_hook(args.root.resolve())
        print("INSTALLED %s" % hook if hook else "NOT INSTALLED: not a git repository, or another pre-commit hook exists")
    findings = audit(args.root)
    if args.changed:
        try:
            findings += changed(args.root, args.changed)
        except ValueError as e:
            print("cannot check changes: %s" % e, file=sys.stderr)
            return 2
    order = {"ERROR": 0, "WARN": 1, "INFO": 2}
    for level, path, msg in sorted(findings, key=lambda f: (order[f[0]], f[1])):
        print("%-5s %s: %s" % (level, path, msg))
    counts = {k: sum(1 for f in findings if f[0] == k) for k in order}
    print("\n%(ERROR)d error(s), %(WARN)d warning(s), %(INFO)d note(s). Structure only: content was not judged." % counts)
    return 1 if counts["ERROR"] else 0


if __name__ == "__main__":
    sys.exit(main())
